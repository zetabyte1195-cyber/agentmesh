// `agentmesh init` (P2.3; spec v1.1 §10.4): writes what a repository needs so agents can connect.
// Never destroys the user's content: rulebooks get a marked section (replaced on re-run, rest
// untouched); MCP config files gain one "agentmesh" entry (other servers kept); config.json is
// only created, never overwritten. Tokens are never written to disk: configs reference
// ${AGENTMESH_TOKEN}.
//
// Shareability additions: it can start a brand-new project (git init in an EMPTY folder only, so it
// never sweeps unknown files into a commit), works out how to test the project from its files, and can
// commit exactly the files it wrote so fresh worktrees contain the rulebooks.
import { existsSync, mkdirSync, readdirSync } from 'node:fs';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { git } from '../git/run-git.js';
import { type CustomPlatformConfig, createRegistry } from '../platforms/index.js';
import { type Bootstrap, detectProject, isEmptyFolder } from './detect.js';

export const SECTION_BEGIN = '<!-- agentmesh:begin (generated by `agentmesh init`; edits inside this block are overwritten) -->';
export const SECTION_END = '<!-- agentmesh:end -->';

export interface InitAgent {
  id: string;
  /** CLAUDE_CODE, ANTIGRAVITY, or the id of a platform in `customPlatforms`. */
  platform: string;
  /** The instruction file that agent's tool reads (CLAUDE.md, GEMINI.md, AGENTS.md...). */
  rulebook: string;
}

export interface InitOptions {
  repoRoot: string;
  port?: number;
  agents?: InitAgent[];
  /** Start a new repository here when the folder is not one. Refused unless the folder is empty. */
  createRepo?: boolean;
  /** Commit the files init wrote (and only those), so new worktrees contain them. Default false here; the CLI turns it on. */
  commit?: boolean;
  /** Platforms beyond the built-in two, written into a NEW config (an existing config is never changed). */
  customPlatforms?: CustomPlatformConfig[];
}

export interface InitReport {
  created: string[];
  updated: string[];
  unchanged: string[];
  config: ProjectConfig;
  /** Set when `git init` was run. */
  repoCreated: boolean;
  /** The commit made for the generated files, if any. */
  committed: string | null;
  /** What was detected about the project, and things the person should know. */
  detected: { kind: string; notes: string[] };
  warnings: string[];
}

export interface ProjectConfig {
  trunk: string;
  verifyCommand: string | null;
  /**
   * Land audited work even though no verifyCommand is set. Only for projects that can't be tested yet
   * (a brand-new project); the other agent's review is then the only gate. Default false.
   */
  landWithoutVerify?: boolean;
  bootstrap: Bootstrap;
  daemon: { port: number };
  agents: InitAgent[];
  /** Platforms beyond Claude Code and Antigravity, defined in config (see platforms/custom.ts). */
  customPlatforms?: CustomPlatformConfig[];
  /** Free text from the Human about the project (stack, conventions, things to avoid). Added to every agent prompt. */
  projectContext?: string;
  /** Where to tell the Human that something needs them (a plan to approve, a question, an agent that gave up). */
  notifications?: { webhookUrl?: string; webhookSecret?: string };
  /** Container mode (EXPERIMENTAL; edited by hand, never from the cockpit): run agents inside containers. See sandbox/config.ts. */
  sandbox?: unknown;
  /** Once a day, ask GitHub whether a newer AgentMesh release exists (contacts github.com; off by default). */
  updateCheck?: boolean;
  /** Project audit checklist (spec v1.1 §9.4); the core gates are always enforced. */
  checklist: { required: string[] };
}

/** init could not proceed; `code` lets the CLI decide what to offer. */
export class InitError extends Error {
  constructor(
    readonly code: 'NOT_A_REPO' | 'NOT_A_REPO_NOT_EMPTY' | 'GIT_IDENTITY' | 'NO_COMMITS',
    message: string,
  ) {
    super(message);
    this.name = 'InitError';
  }
}

export const DEFAULT_AGENTS: InitAgent[] = [
  { id: 'claude-1', platform: 'CLAUDE_CODE', rulebook: 'CLAUDE.md' },
  { id: 'gemini-1', platform: 'ANTIGRAVITY', rulebook: 'GEMINI.md' },
];

async function repoRootOf(dir: string): Promise<string | null> {
  try {
    return resolve((await git(dir, ['rev-parse', '--show-toplevel'])).trim());
  } catch {
    return null;
  }
}

async function configValue(root: string, key: string): Promise<string> {
  try {
    return (await git(root, ['config', '--get', key])).trim();
  } catch {
    return '';
  }
}

/** Agents commit with the repository's git identity; without one every mesh_commit would fail. */
export async function requireGitIdentity(root: string): Promise<void> {
  const [name, email] = await Promise.all([configValue(root, 'user.name'), configValue(root, 'user.email')]);
  if (name && email) return;
  // Git also takes an identity from the environment; the daemon passes its environment to every commit it makes.
  if (process.env.GIT_AUTHOR_NAME && process.env.GIT_AUTHOR_EMAIL && process.env.GIT_COMMITTER_NAME && process.env.GIT_COMMITTER_EMAIL) return;
  throw new InitError(
    'GIT_IDENTITY',
    `Git has no ${!name && !email ? 'name or email' : !name ? 'name' : 'email'} set, and AgentMesh's agents commit with it.\n` +
      '  Set it for this project:  git config user.name "Your Name" && git config user.email "you@example.com"\n' +
      '  or for every project:     git config --global user.name "Your Name" && git config --global user.email "you@example.com"',
  );
}

export async function initProject(options: InitOptions): Promise<InitReport> {
  const dir = resolve(options.repoRoot);
  let root = await repoRootOf(dir);
  let repoCreated = false;
  if (!root) {
    if (!options.createRepo) {
      throw new InitError(
        isEmptyFolder(dir) ? 'NOT_A_REPO' : 'NOT_A_REPO_NOT_EMPTY',
        isEmptyFolder(dir)
          ? `${dir} is not a git repository. It is empty, so AgentMesh can start one here: run again with --yes.`
          : `${dir} is not a git repository, and it has files in it. Agents work on branches of a git repository, and AgentMesh will not guess which of your files to commit.\n  Review them and run:  git init && git add -A && git commit -m "Initial commit"\n  then run this again.`,
      );
    }
    if (!isEmptyFolder(dir)) {
      throw new InitError('NOT_A_REPO_NOT_EMPTY', `${dir} has files in it; AgentMesh only starts a new repository in an empty folder. Run "git init" and make the first commit yourself, then run this again.`);
    }
    mkdirSync(dir, { recursive: true });
    await git(dir, ['init', '-q', '-b', 'main']);
    root = dir;
    repoCreated = true;
  }
  await requireGitIdentity(root);

  const port = options.port ?? 8934;
  const agents = options.agents ?? DEFAULT_AGENTS;
  const configPath = join(root, '.agentmesh', 'config.json');
  const detection = detectProject(root);
  const trunk = (await git(root, ['symbolic-ref', '--quiet', '--short', 'HEAD']).catch(() => 'main')).trim() || 'main';
  const fresh: ProjectConfig = {
    trunk,
    verifyCommand: detection.verifyCommand, // null → landing stays off until the Human sets one (or opts in to landWithoutVerify)
    // A brand-new project has nothing to test yet; refusing to land anything until someone edits JSON would stall
    // the very first task. The other agent's review still gates it, and every screen says so.
    ...(detection.kind === 'empty' && !detection.verifyCommand ? { landWithoutVerify: true } : {}),
    bootstrap: detection.bootstrap,
    daemon: { port },
    agents,
    customPlatforms: options.customPlatforms ?? [],
    checklist: { required: [] },
  };
  const report: InitReport = { created: [], updated: [], unchanged: [], config: fresh, repoCreated, committed: null, detected: { kind: detection.kind, notes: detection.notes }, warnings: [] };
  const record = (file: string, outcome: 'created' | 'updated' | 'unchanged') => report[outcome].push(file);

  // 1. Project config: create once, never overwrite (the Human may have tuned it).
  if (existsSync(configPath)) {
    record('.agentmesh/config.json', 'unchanged');
    report.config = JSON.parse(await readFile(configPath, 'utf8')) as ProjectConfig;
  } else {
    await writeText(configPath, `${JSON.stringify(fresh, null, 2)}\n`);
    record('.agentmesh/config.json', 'created');
  }

  // Every platform an agent uses must be known (built in, or defined in this config).
  const registry = createRegistry(report.config.customPlatforms ?? []);
  for (const a of report.config.agents) {
    if (!registry.has(a.platform)) throw new Error(`Agent ${a.id} uses platform "${a.platform}", which is neither built in nor defined in customPlatforms`);
  }
  const friendly = (platform: string) => registry.get(platform)?.friendlyName ?? platform;
  const rulebookNotes = (platform: string) => (platform === 'ANTIGRAVITY' ? ANTIGRAVITY_HEADLESS : '');

  // Files this run writes that belong in git; remember which already had uncommitted changes of the user's.
  const tracked: string[] = [];
  const dirty = new Set<string>();
  const dirtyBefore = async (file: string) => {
    if (existsSync(join(root!, file)) && (await git(root!, ['status', '--porcelain', '--', file])).trim()) dirty.add(file);
  };

  // 2. MCP configs, one entry each (formats verified with `claude mcp add` / `agy mcp add`).
  const url = `http://127.0.0.1:${report.config.daemon.port}/mcp`;
  const headers = { Authorization: 'Bearer ${AGENTMESH_TOKEN}' };
  for (const f of ['.mcp.json', '.agents/mcp_config.json']) await dirtyBefore(f);
  record('.mcp.json', await mergeJsonEntry(join(root, '.mcp.json'), 'agentmesh', { type: 'http', url, headers }));
  record('.agents/mcp_config.json', await mergeJsonEntry(join(root, '.agents', 'mcp_config.json'), 'agentmesh', { serverUrl: url, headers, disabled: false }));
  tracked.push('.mcp.json', '.agents/mcp_config.json');

  // 3. Rulebooks: one marked section per platform's file.
  const cfgAgents = report.config.agents;
  for (const file of new Set(cfgAgents.map((a) => a.rulebook))) {
    await dirtyBefore(file);
    record(file, await upsertSection(join(root, file), rulebook(file, cfgAgents, friendly, rulebookNotes)));
    tracked.push(file);
  }

  // 4. Keep .agentmesh/ (worktrees, DB) out of `git status` without touching .gitignore.
  const exclude = join(resolve(root, (await git(root, ['rev-parse', '--git-common-dir'])).trim()), 'info', 'exclude');
  const current = existsSync(exclude) ? await readFile(exclude, 'utf8') : '';
  if (current.split(/\r?\n/).includes('/.agentmesh/')) {
    record('.git/info/exclude', 'unchanged');
  } else {
    await writeText(exclude, `${current}${current && !current.endsWith('\n') ? '\n' : ''}/.agentmesh/\n`);
    record('.git/info/exclude', current ? 'updated' : 'created');
  }

  // 5. Commit exactly what we wrote, so worktrees (which branch from the last commit) contain it.
  if (options.commit) {
    const changed = [...report.created, ...report.updated].filter((f) => tracked.includes(f));
    const safe = changed.filter((f) => !dirty.has(f));
    for (const f of changed.filter((x) => dirty.has(x))) report.warnings.push(`${f} had your own uncommitted changes, so it was not committed; commit it yourself.`);
    if (safe.length) {
      await git(root, ['add', '--', ...safe]);
      await git(root, ['commit', '-q', '-m', 'AgentMesh setup (agentmesh init)', '--', ...safe]);
      report.committed = (await git(root, ['rev-parse', '--short', 'HEAD'])).trim();
    }
  }
  if (!(await git(root, ['rev-parse', '--verify', '-q', 'HEAD']).then(() => true, () => false))) {
    report.warnings.push('This repository has no commits yet, and agents need one to branch from. Commit something (or run init with --commit).');
  }
  return report;
}

/** Folders init may leave behind; kept here so callers can show what "empty" allows. */
export function listFolder(dir: string): string[] {
  try {
    return readdirSync(dir);
  } catch {
    return [];
  }
}

async function writeText(path: string, text: string): Promise<void> {
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, text);
}

/** Set mcpServers[name] = entry, keeping every other server and key. */
async function mergeJsonEntry(path: string, name: string, entry: unknown): Promise<'created' | 'updated' | 'unchanged'> {
  const exists = existsSync(path);
  const data = exists ? (JSON.parse(await readFile(path, 'utf8')) as { mcpServers?: Record<string, unknown> }) : {};
  const before = JSON.stringify(data.mcpServers?.[name] ?? null);
  data.mcpServers = { ...(data.mcpServers ?? {}), [name]: entry };
  if (exists && before === JSON.stringify(entry)) return 'unchanged';
  await writeText(path, `${JSON.stringify(data, null, 2)}\n`);
  return exists ? 'updated' : 'created';
}

/** Insert or replace the marked AgentMesh section; everything outside it is left byte-for-byte. */
async function upsertSection(path: string, body: string): Promise<'created' | 'updated' | 'unchanged'> {
  const block = `${SECTION_BEGIN}\n${body.trim()}\n${SECTION_END}`;
  if (!existsSync(path)) {
    await writeText(path, `${block}\n`);
    return 'created';
  }
  const text = await readFile(path, 'utf8');
  const start = text.indexOf(SECTION_BEGIN);
  const end = text.indexOf(SECTION_END);
  const next = start >= 0 && end > start ? text.slice(0, start) + block + text.slice(end + SECTION_END.length) : `${text}${text.endsWith('\n') ? '\n' : '\n\n'}${block}\n`;
  if (next === text) return 'unchanged';
  await writeFile(path, next);
  return 'updated';
}

/** Headless agy refuses any tool without an allow rule, and one refusal ends the run (verified during this build). */
const ANTIGRAVITY_HEADLESS = `
**Headless runs (\`agy -p\`)**
- There is no permission prompt in headless mode: any tool or command without an allow rule in \`~/.gemini/antigravity-cli/settings.json\` is refused, and **one refusal ends your whole run**.
- Work with files inside your worktree and the \`mesh_*\` tools. Do not run shell commands: check your work with \`mesh_run_verification\` and commit with \`mesh_commit\`.
- If the person added \`command(...)\` allow rules, they match the **entire command line exactly**: \`command(git status)\` does not allow \`git status --short\`. Run such a command character for character and never add arguments.
- Files of the main repository **outside your worktree** (e.g. its \`.agentmesh/\` folder, which is local and not in the worktree) are refused too, and that also ends the run.
`;

function rulebook(file: string, agents: InitAgent[], friendly: (platform: string) => string, notes: (platform: string) => string): string {
  const mine = agents.filter((a) => a.rulebook === file);
  const me = mine.map((a) => `\`${a.id}\``).join(', ');
  const others = [...new Set(agents.filter((a) => a.rulebook !== file).map((a) => friendly(a.platform)))].join(' or ') || 'another platform';
  const extra = [...new Set(mine.map((a) => notes(a.platform)).filter(Boolean))].join('');
  return `
## AgentMesh: how to work in this repository

You are ${me || 'an agent'} on this repository's AgentMesh board. Several agents work here in parallel; a Human watches the cockpit and steers.

**Every session**
1. Call \`mesh_get_board\` first. Your identity comes from your token (\`AGENTMESH_TOKEN\`), never from an argument.
2. Act on handoffs addressed to you and on audits waiting for you before starting new work.
3. Keep \`mesh_set_status\` current in one sentence; set it to \`idle\` when you stop.

**Working a task**
1. \`mesh_claim_task\`. It returns your own git worktree; work **only** there.
2. \`mesh_acquire_lease\` every file you edit before you edit it. Lease individual FILES, not a whole folder, when another task may work in the same folder (a folder lease blocks everyone else there). Unleased changes are rejected.
3. Check your work with \`mesh_run_verification\` (the daemon runs the project's checks for you), commit with \`mesh_commit\` (the daemon runs git for you; no shell git needed), then \`mesh_submit_for_review\`. The daemon pins the exact diff.
4. Record verified facts with \`mesh_log_finding\`, decisions with \`mesh_record_decision\`, and product questions for the Human with \`mesh_ask_question\`.

**Reviewing (two-platform rule)**
- Never audit your own work or work from your own platform. Audits of your work come from ${others} or the Human.
- An audit is real checking: read the pinned diff with \`mesh_get_diff\`, run the project checks with \`mesh_run_verification\`, compare with the acceptance criteria, then \`mesh_submit_audit\` with the pinned \`diffHash\` and an explicit \`testRunSuccess\`.

**Missions (planning)**
- When you are asked to plan or review a plan, use \`mesh_get_mission\`, \`mesh_submit_plan\`, \`mesh_submit_plan_review\` and \`mesh_finish_split\`. Planning runs happen in a scratch copy: your edits there are thrown away.

**Ground rules**
- Do not assume or invent: verify against code, docs or command output, or say you couldn't verify it.
- Never push, never rewrite shared history, never touch files outside your worktree.
${extra}`;
}
